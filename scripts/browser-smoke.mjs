const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const siteUrl = process.env.SITE_URL || 'http://127.0.0.1:3001';
const qaDir = process.env.QA_DIR || '/tmp/visiongo-qa';
import assert from 'node:assert/strict';
import fs from 'node:fs';
const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || '/usr/bin/google-chrome', headless: true, args: ['--no-sandbox', '--disable-dev-shm-usage'] });
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
const page = await context.newPage();
const errors = [];
page.on('pageerror', error => errors.push(error.message));
page.on('console', message => { if (message.type() === 'error' && /Hydration|Minified React|hydrated/.test(message.text())) errors.push(message.text()); });
await page.route('**/api/auth/**', route => route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify(route.request().url().endsWith('/config') ? { googleClientId: null, githubClientId: null } : { user: null }) }));
let mode = 'error';
await page.route('**/api/releases?*', route => route.fulfill({ status: mode === 'error' ? 503 : 200, contentType: 'application/json', body: JSON.stringify({ success: mode !== 'error', releases: { visionstudio: mode === 'empty' ? [] : [{ product: 'visionstudio', version: 'v1.0', name: 'Test release', publishedAt: '2026-10-14T00:00:00Z', description: 'Test release notes', prerelease: false, assets: [{ id: '42', name: 'studio-linux-arm64.tar.gz', platform: 'linux', arch: 'arm64', size: 1048576, downloadUrl: '/api/download/visionstudio/42' }] }], visionruntime: [], visionedge: [] } }) }));
let contactStatus = 503;
const submissions = [];
await page.route('**/api/contact', async route => {
  submissions.push(route.request().postDataJSON());
  await route.fulfill({ status: contactStatus, contentType: 'application/json', body: JSON.stringify(contactStatus === 503 ? { error: 'Storage unavailable. Retry later.' } : { success: true, referenceId: 'VG-browser-test' }) });
});
fs.mkdirSync(qaDir, { recursive: true });
try {
  for (const width of [375, 768, 1024, 1440]) {
    await page.setViewportSize({ width, height: 1000 });
    await page.goto(`${siteUrl}/zh`);
    await page.getByRole('heading', { level: 1 }).waitFor();
    await page.waitForFunction(() => document.querySelector('img')?.complete);
    assert.ok(await page.getByRole('link', { name: '下载 VisionStudio', exact: true }).isVisible());
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), `overflow at ${width}`);
    await page.screenshot({ path: `${qaDir}/home-zh-${width}.png`, fullPage: true });
  }
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.getByRole('button', { name: '预约产品演示' }).click();
  const dialog = page.getByRole('dialog'); await dialog.waitFor();
  assert.ok(await dialog.evaluate(el => el.contains(document.activeElement)));
  await page.keyboard.press('Shift+Tab'); assert.ok(await dialog.evaluate(el => el.contains(document.activeElement)));
  await page.keyboard.press('Escape'); assert.equal(await dialog.count(), 0);
  await page.getByRole('link', { name: '快速开始', exact: true }).first().click();
  await page.getByRole('heading', { name: '快速开始', exact: true }).waitFor();
  assert.equal(new URL(page.url()).pathname, '/zh/developers'); assert.equal(new URL(page.url()).hash, '#quickstart');
  await page.goto(`${siteUrl}/zh/resources`);
  await page.getByRole('link', { name: /开始使用 VisionStudio 与 VisionRuntime/ }).click();
  await page.getByRole('heading', { level: 1, name: '开始使用 VisionStudio 与 VisionRuntime' }).waitFor();
  assert.equal(new URL(page.url()).pathname, '/zh/resources/getting-started');
  await page.reload(); await page.getByRole('heading', { level: 1, name: '开始使用 VisionStudio 与 VisionRuntime' }).waitFor();
  await page.goBack(); await page.getByRole('heading', { level: 1, name: '工程资源与指南' }).waitFor();
  await page.goto(`${siteUrl}/zh/downloads`);
  await page.getByText('暂时无法获取发行版本，请重试。').first().waitFor();
  mode = 'ready'; await page.getByRole('button', { name: '重新加载' }).first().click();
  await page.getByRole('combobox').first().waitFor();
  const studio = page.getByRole('article').filter({ has: page.getByRole('heading', { name: 'VisionStudio', exact: true }) });
  await studio.getByRole('combobox', { name: '系统、架构与安装包' }).selectOption('42');
  assert.equal(await studio.getByRole('link', { name: '下载所选安装包' }).getAttribute('href'), '/api/download/visionstudio/42');
  await studio.getByRole('button', { name: '更新日志与版本说明' }).click();
  await page.getByRole('dialog').waitFor(); await page.keyboard.press('Escape');
  mode = 'empty'; await page.getByRole('checkbox').check(); await page.getByText('当前通道暂无已发布版本。').first().waitFor();
  await page.goto(`${siteUrl}/zh/contact`);
  await page.getByLabel('姓名 *', { exact: true }).fill('Test Engineer');
  await page.getByLabel('邮箱 *', { exact: true }).fill('engineer@example.com');
  await page.getByLabel('项目描述 *', { exact: true }).fill('Test inquiry for browser QA.');
  await page.getByRole('button', { name: '提交工程咨询' }).click(); await page.getByRole('alert').waitFor();
  assert.equal(await page.getByText('咨询已保存', { exact: true }).count(), 0);
  contactStatus = 201; await page.getByRole('button', { name: '提交工程咨询' }).click();
  await page.getByRole('heading', { name: '咨询已保存' }).waitFor();
  assert.equal(submissions.length, 2); assert.equal(submissions[0].submissionId, submissions[1].submissionId);
  await page.goto(`${siteUrl}/zh/unknown`); await page.getByRole('heading', { name: '页面不存在' }).waitFor();
  await page.goto(`${siteUrl}/`); await page.getByRole('heading', { level: 1 }).waitFor();
  await page.getByTitle('Switch Language / 切换语言').click(); await page.getByRole('button', { name: '简体中文' }).click();
  await page.getByRole('heading', { level: 1, name: /构建、调试并部署/ }).waitFor(); assert.equal(new URL(page.url()).pathname, '/zh');
  await page.goBack(); await page.getByRole('heading', { level: 1, name: /Build, debug and deploy/ }).waitFor();
  assert.deepEqual(errors, []);
  console.log('Browser smoke passed: four responsive widths, localized navigation, article refresh/back, dialogs, download states/package selection, contact retry and 404.');
} finally { await browser.close(); }
